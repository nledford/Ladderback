//! Embeds the catalogs and generates the message IDs (technical design §8.4).
//!
//! Every `locales/<tag>/*.ftl` is checked with `fluent-syntax` and embedded
//! with `include_str!`, so a catalog with a syntax error fails the build, and
//! nothing is read at run time. `en-US` is the source locale: `msg.rs` gets
//! one constant per message in it, so an ID that isn't in the catalog doesn't
//! compile and the constants can't drift from it.

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use fluent_syntax::ast::Entry;
use fluent_syntax::parser;
use unic_langid::LanguageIdentifier;

#[path = "src/constants.rs"]
mod constants;

const SOURCE_TAG: &str = "en-US";

type Result<T, E = Box<dyn Error>> = std::result::Result<T, E>;

/// One locale's directory.
struct Locale {
    tag: String,
    files: Vec<File>,
}

/// One `.ftl` file.
struct File {
    name: String,
    path: PathBuf,
    text: String,
}

fn main() -> Result<()> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=src/constants.rs");
    println!("cargo::rerun-if-changed=locales");

    let locales = read_locales(&manifest.join("locales"))?;
    let source = locales
        .iter()
        .find(|locale| locale.tag == SOURCE_TAG)
        .ok_or("locales/en-US is missing: it is the source locale")?;
    fs::write(out.join("catalog.rs"), catalog_table(&locales)?)?;
    fs::write(out.join("msg.rs"), message_constants(source)?)?;
    Ok(())
}

/// The entries of `dir`, by name, so the output doesn't depend on the order
/// the file system lists them in.
fn sorted_entries(dir: &Path) -> Result<Vec<fs::DirEntry>> {
    let mut entries = fs::read_dir(dir)
        .map_err(|error| format!("cannot read {}: {error}", dir.display()))?
        .collect::<std::io::Result<Vec<_>>>()?;
    entries.sort_by_key(fs::DirEntry::file_name);
    Ok(entries)
}

fn read_locales(dir: &Path) -> Result<Vec<Locale>> {
    let mut locales = Vec::new();
    for entry in sorted_entries(dir)? {
        if !entry.file_type()?.is_dir() {
            continue;
        }
        let tag = entry
            .file_name()
            .into_string()
            .map_err(|name| format!("{name:?} is not a UTF-8 locale name"))?;
        // The tag becomes a Rust string and, at run time, a language
        // identifier. It never becomes a path: the files are embedded here.
        let parsed: LanguageIdentifier = tag
            .parse()
            .map_err(|error| format!("locales/{tag} is not a language tag: {error}"))?;
        if parsed.to_string() != tag {
            return Err(format!("locales/{tag} must be named {parsed}").into());
        }
        let mut files = Vec::new();
        for file in sorted_entries(&entry.path())? {
            let path = file.path();
            if path.extension().is_none_or(|extension| extension != "ftl") {
                continue;
            }
            let name = file.file_name().to_string_lossy().into_owned();
            let text = fs::read_to_string(&path)
                .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
            check_syntax(&tag, &name, &text)?;
            files.push(File { name, path, text });
        }
        locales.push(Locale { tag, files });
    }
    Ok(locales)
}

/// Fails on any syntax error, naming the file and each error's line.
fn check_syntax(tag: &str, name: &str, text: &str) -> Result<()> {
    let Err((_, errors)) = parser::parse(text) else {
        return Ok(());
    };
    let mut report = format!("locales/{tag}/{name} has syntax errors:");
    for error in errors {
        let line = text[..error.pos.start.min(text.len())]
            .bytes()
            .filter(|byte| *byte == b'\n')
            .count()
            + 1;
        write!(report, "\n  line {line}: {error}")?;
    }
    Err(report.into())
}

/// The table of embedded catalogs: `catalog::CATALOGS`.
fn catalog_table(locales: &[Locale]) -> Result<String> {
    let mut code = String::from("// @generated by build.rs from locales/\n");
    code.push_str("pub(crate) const CATALOGS: &[Catalog] = &[\n");
    for locale in locales {
        writeln!(
            code,
            "    Catalog {{\n        tag: {:?},\n        sources: &[",
            locale.tag
        )?;
        for file in &locale.files {
            let path = file
                .path
                .to_str()
                .ok_or_else(|| format!("{} is not a UTF-8 path", file.path.display()))?;
            writeln!(
                code,
                "            Source {{ name: {:?}, text: include_str!({path:?}) }},",
                file.name
            )?;
        }
        code.push_str("        ],\n    },\n");
    }
    code.push_str("];\n");
    Ok(code)
}

/// `msg.rs`: a constant for each message of the source locale, and `ALL`.
fn message_constants(source: &Locale) -> Result<String> {
    let parsed: Vec<_> = source
        .files
        .iter()
        .map(|file| {
            let resource = match parser::parse(file.text.as_str()) {
                Ok(resource) | Err((resource, _)) => resource,
            };
            (file.name.as_str(), resource)
        })
        .collect();
    let ids = parsed.iter().flat_map(|(file, resource)| {
        resource.body.iter().filter_map(move |entry| match entry {
            Entry::Message(message) => Some((*file, message.id.name)),
            _ => None,
        })
    });
    let constants = constants::constants(ids)?;
    let mut code = String::from("// @generated by build.rs from locales/en-US\n");
    for (name, id) in &constants {
        writeln!(
            code,
            "/// `{id}`\npub const {name}: MessageId = MessageId::new({id:?});"
        )?;
    }
    code.push_str("\n/// Every message of the source catalog.\npub const ");
    code.push_str(constants::RESERVED);
    code.push_str(": &[MessageId] = &[\n");
    for (name, _) in &constants {
        writeln!(code, "    {name},")?;
    }
    code.push_str("];\n");
    Ok(code)
}
